#!/usr/bin/env python3
"""
Waycord Centralized Organization & Legal Metadata Synchronizer

Reads config/organization.json as the single source of truth and cascades updates to:
1. helm/assets/config/organization.json (runtime asset mirror)
2. helm/lib/core/config/brand_config.dart (Dart code constants)
3. PRIVACY_POLICY.md (repo root and helm/assets/Privacy_policy.md)
4. EULA.md (repo root and helm/assets/EULA.md)
5. README.md (repo root and helm/README.md)
"""

import json
import os
import re

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG_PATH = os.path.join(ROOT_DIR, "config", "organization.json")
ASSET_CONFIG_PATH = os.path.join(ROOT_DIR, "helm", "assets", "config", "organization.json")
DART_CONFIG_PATH = os.path.join(ROOT_DIR, "helm", "lib", "core", "config", "brand_config.dart")
TEMPLATES_DIR = os.path.join(ROOT_DIR, "tools", "templates")


def load_config():
    if not os.path.exists(CONFIG_PATH):
        raise FileNotFoundError(f"Configuration file not found: {CONFIG_PATH}")
    with open(CONFIG_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def mirror_json(config):
    os.makedirs(os.path.dirname(ASSET_CONFIG_PATH), exist_ok=True)
    with open(ASSET_CONFIG_PATH, "w", encoding="utf-8") as f:
        json.dump(config, f, indent=2)
    print(f"✓ Mirrored config to {ASSET_CONFIG_PATH}")


def generate_dart_config(config):
    os.makedirs(os.path.dirname(DART_CONFIG_PATH), exist_ok=True)
    app_name = config.get("app_name", "Waycord")
    app_domain = config.get("app_domain", "waycord.org")
    org_name = config.get("organization_name", "[INSERT_LEGAL_ENTITY_NAME_HERE]")
    support_email = config.get("support_email", "support@waycord.org")
    privacy_email = config.get("privacy_email", "privacy@waycord.org")
    legal_email = config.get("legal_email", "legal@waycord.org")
    jurisdiction = config.get("jurisdiction", "India")
    data_region = config.get("data_region", "ap-south-1 (Mumbai)")

    dart_code = f"""// Generated by tools/sync_brand_docs.py. Do not edit directly.
// Source: config/organization.json

/// Centralized brand and organization configuration constants.
class BrandConfig {{
  const BrandConfig._();

  static const String appName = '{app_name}';
  static const String appDomain = '{app_domain}';
  static const String organizationName = '{org_name}';
  static const String supportEmail = '{support_email}';
  static const String privacyEmail = '{privacy_email}';
  static const String legalEmail = '{legal_email}';
  static const String jurisdiction = '{jurisdiction}';
  static const String dataRegion = '{data_region}';
}}
"""
    with open(DART_CONFIG_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(dart_code)
    print(f"✓ Generated Dart brand constants: {DART_CONFIG_PATH}")


def render_template(template_text, config):
    rendered = template_text
    replacements = {
        "{{app_name}}": config.get("app_name", "Waycord"),
        "{{app_domain}}": config.get("app_domain", "waycord.org"),
        "{{organization_name}}": config.get("organization_name", "[INSERT_LEGAL_ENTITY_NAME_HERE]"),
        "{{support_email}}": config.get("support_email", "support@waycord.org"),
        "{{privacy_email}}": config.get("privacy_email", "privacy@waycord.org"),
        "{{legal_email}}": config.get("legal_email", "legal@waycord.org"),
        "{{jurisdiction}}": config.get("jurisdiction", "India"),
        "{{data_region}}": config.get("data_region", "ap-south-1 (Mumbai)"),
    }
    for placeholder, val in replacements.items():
        rendered = rendered.replace(placeholder, str(val))
    return rendered


def sync_legal_docs(config):
    # 1. Privacy Policy
    privacy_template = os.path.join(TEMPLATES_DIR, "PRIVACY_POLICY.template.md")
    if os.path.exists(privacy_template):
        with open(privacy_template, "r", encoding="utf-8") as f:
            content = f.read()
        rendered_privacy = render_template(content, config)
        
        target_privacy_files = [
            os.path.join(ROOT_DIR, "PRIVACY_POLICY.md"),
            os.path.join(ROOT_DIR, "helm", "assets", "Privacy_policy.md"),
        ]
        for p in target_privacy_files:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w", encoding="utf-8", newline="\n") as f:
                f.write(rendered_privacy)
            print(f"✓ Synchronized Privacy Policy: {p}")

    # 2. EULA
    eula_template = os.path.join(TEMPLATES_DIR, "EULA.template.md")
    if os.path.exists(eula_template):
        with open(eula_template, "r", encoding="utf-8") as f:
            content = f.read()
        rendered_eula = render_template(content, config)

        target_eula_files = [
            os.path.join(ROOT_DIR, "EULA.md"),
            os.path.join(ROOT_DIR, "helm", "assets", "EULA.md"),
        ]
        for p in target_eula_files:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w", encoding="utf-8", newline="\n") as f:
                f.write(rendered_eula)
            print(f"✓ Synchronized EULA: {p}")


def sync_readme(config):
    readme_template = os.path.join(TEMPLATES_DIR, "README.template.md")
    if os.path.exists(readme_template):
        with open(readme_template, "r", encoding="utf-8") as f:
            content = f.read()
        rendered_readme = render_template(content, config)

        readme_paths = [
            os.path.join(ROOT_DIR, "README.md"),
            os.path.join(ROOT_DIR, "helm", "README.md"),
        ]
        for r_path in readme_paths:
            os.makedirs(os.path.dirname(r_path), exist_ok=True)
            with open(r_path, "w", encoding="utf-8", newline="\n") as f:
                f.write(rendered_readme)
            print(f"✓ Synchronized Readme: {r_path}")


def sync():
    config = load_config()
    print(f"Starting brand and legal metadata synchronization...")
    mirror_json(config)
    generate_dart_config(config)
    sync_legal_docs(config)
    sync_readme(config)
    print("Synchronization successfully completed!")


if __name__ == "__main__":
    sync()
